/**
 * Checks if an error is caused by PostgreSQL Row Level Security (RLS).
 */
export const isRlsError = (error) => {
  if (!error) return false;
  const msg = (error.message || '').toLowerCase();
  return (
    error.code === '42501' ||
    msg.includes('row-level security') ||
    msg.includes('violates row-level') ||
    msg.includes('violates rls')
  );
};

let cachedSchemaStatus = null;

/**
 * Check whether Supabase tables exist and whether RLS permits writes.
 * Times out in 3 seconds to avoid blocking the app.
 */
export const checkSupabaseSchema = async () => {
  if (!isSupabaseEnabled()) return { status: 'offline' };
  if (cachedSchemaStatus && cachedSchemaStatus.status === 'ready') return cachedSchemaStatus;

  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 3000);

    // Non-destructive probe insert to test table existence and RLS write permission
    const { error } = await supabase
      .from('trips')
      .insert([{}])
      .abortSignal(controller.signal);
    clearTimeout(timer);

    if (error) {
      if (error.code === 'PGRST205') {
        cachedSchemaStatus = { status: 'needs_schema', error: error.message };
        return cachedSchemaStatus;
      }
      if (isRlsError(error)) {
        cachedSchemaStatus = { status: 'rls_blocked', error: error.message };
        return cachedSchemaStatus;
      }
      // Any other error (e.g. 23502 not-null constraint violation) means RLS allows writes!
      cachedSchemaStatus = { status: 'ready' };
      return cachedSchemaStatus;
    }

    cachedSchemaStatus = { status: 'ready' };
    return cachedSchemaStatus;
  } catch (_) {
    cachedSchemaStatus = { status: 'ready' };
    return cachedSchemaStatus;
  }
};

export const getCachedSchemaStatus = () => cachedSchemaStatus;
export const setCachedSchemaStatus = (status) => { cachedSchemaStatus = status; };

// Normalizer: Supabase Row -> App Trip Object
export const mapTripFromSupabase = (row) => {
  let remarks = row.remarks || '';
  let commission = Number(row.commission) || 0;
  let height = row.height || '';
  let transactions = Array.isArray(row.transactions) ? row.transactions : [];

  // Parse TX_META comment if embedded in remarks
  if (remarks.includes('<!--TX_META:')) {
    const match = remarks.match(/<!--TX_META:([\s\S]*?)-->/);
    if (match) {
      try {
        const meta = JSON.parse(match[1]);
        if (meta.commission !== undefined && !commission) {
          commission = Number(meta.commission) || 0;
        }
        if (meta.height && !height) {
          height = meta.height;
        }
        if (Array.isArray(meta.transactions) && transactions.length === 0) {
          transactions = meta.transactions;
        }
      } catch {}
      remarks = remarks.replace(/<!--TX_META:[\s\S]*?-->/g, '').trim();
    }
  }

  return {
    id: row.id,
    lrNo: row.lr_no || row.lrNo || '',
    partyName: row.party_name || row.partyName || '',
    partyPhone: row.party_phone || row.partyPhone || '',
    vehicleNo: row.vehicle_no || row.vehicleNo || '',
    vehicleType: row.vehicle_type || row.vehicleType || '14 Wheeler',
    fromCity: row.from_city || row.fromCity || '',
    toCity: row.to_city || row.toCity || '',
    date: row.date || row.trip_date || '',
    material: row.material || '',
    weight: row.weight || '',
    height: height,
    driverName: row.driver_name || row.driverName || '',
    driverMobile: row.driver_mobile || row.driverMobile || '',
    amount: Number(row.amount) || 0,
    advance: Number(row.advance) || 0,
    balance: Number(row.balance) || 0,
    commission: commission,
    transactions: transactions,
    paymentStatus: row.payment_status || row.paymentStatus || 'Pending',
    deliveryStatus: row.delivery_status || row.deliveryStatus || 'Booked',
    remarks: remarks,
    createdAt: row.created_at || row.createdAt || new Date().toISOString()
  };
};

// Converter: App Trip Object -> Supabase Row
export const mapTripToSupabase = (trip) => {
  let remarksText = (trip.remarks || '').replace(/<!--TX_META:[\s\S]*?-->/g, '').trim();
  const meta = {
    commission: Number(trip.commission) || 0,
    height: trip.height || '',
    transactions: Array.isArray(trip.transactions) ? trip.transactions : []
  };
  const combinedRemarks = remarksText 
    ? `${remarksText}\n<!--TX_META:${JSON.stringify(meta)}-->`
    : `<!--TX_META:${JSON.stringify(meta)}-->`;

  const payload = {
    lr_no: trip.lrNo || '',
    party_name: trip.partyName || '',
    party_phone: trip.partyPhone || '',
    vehicle_no: trip.vehicleNo || '',
    vehicle_type: trip.vehicleType || '',
    from_city: trip.fromCity || '',
    to_city: trip.toCity || '',
    date: trip.date || '',
    material: trip.material || '',
    weight: trip.weight || '',
    driver_name: trip.driverName || '',
    driver_mobile: trip.driverMobile || '',
    amount: Number(trip.amount) || 0,
    advance: Number(trip.advance) || 0,
    balance: Number(trip.balance) || 0,
    payment_status: trip.paymentStatus || 'Pending',
    delivery_status: trip.deliveryStatus || 'Booked',
    remarks: combinedRemarks,
    updated_at: new Date().toISOString()
  };
  if (trip.height) {
    payload.height = trip.height;
  }
  if (trip.id && typeof trip.id === 'number') {
    payload.id = trip.id;
  }
  return payload;
};

